import "server-only";
import { enqueueJob, getEnv } from "@/modules/platform/service";
import { type BenchmarkUpload, configHash, envFingerprint, sha256 } from "./contract.ts";
import * as repo from "./repo.ts";
import { describe } from "./summary.ts";

/** Deterministic PRNG (mulberry32) so the sample project is identical every time it is created. */
function rng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Log-normal latencies with a small slow tail, rounded to 0.01 ms. */
function latencies(r: () => number, n: number, medianMs: number) {
  return Array.from({ length: n }, () => {
    const z = Math.sqrt(-2 * Math.log(1 - r())) * Math.cos(2 * Math.PI * r());
    const tail = r() < 0.02 ? 3 : 1;
    return Math.round(medianMs * Math.exp(0.25 * z) * tail * 100) / 100;
  });
}

const ENV: BenchmarkUpload["env"] = {
  cpu: "SAMPLE DATA CPU (8 cores)", cpu_count: 8, memory_mb: 16384, os: "Linux (sample)", python: "3.12", libs: { "sample-server": "1.0.0" },
  git_sha: null, container_digest: null, gpu: [],
};

/**
 * Seeds one is_mock project: "batch=1" (baseline) vs "batch=8", five runs each plus a warm-up and a failed run.
 * Labelled everywhere with the SAMPLE DATA banner; excluded from meters, portfolio and reports (AT-20).
 */
export async function seedSampleProject(userId: string, now = new Date()) {
  const projectId = await repo.createProject(userId, {
    title: "SAMPLE DATA: request batching vs latency",
    hypothesis: "Batching 8 requests lowers p50 latency of the toy inference server compared with batch size 1.",
    planMd: "Sample project generated by Systems Atlas to demonstrate the lab. None of these numbers are real measurements.",
  }, true);
  await repo.updateProject(projectId, {
    status: "running", preregisteredAt: now, minRepetitions: 5,
    preregJson: { primary_metric: "latency_ms", baseline_desc: "batch size 1", stopping_rule: "5 ok runs per config", min_repetitions: 5 },
  });
  const r = rng(20261118);
  const plan = [
    ...Array.from({ length: 6 }, (_, i) => ({ name: "batch=1", config: { batch_size: 1 }, median: 20, baseline: true, warmup: i === 0, failed: false })),
    ...Array.from({ length: 6 }, (_, i) => ({ name: "batch=8", config: { batch_size: 8 }, median: 15, baseline: false, warmup: false, failed: i === 5 })),
  ];
  let minute = 0;
  for (const p of plan) {
    const samples = p.failed ? [] : latencies(r, 500, p.median);
    const started = new Date(now.getTime() - (60 - minute++) * 60_000);
    const upload: BenchmarkUpload = {
      schema_version: "1", project_id: projectId, config_name: p.name, config: p.config, config_hash: configHash(p.config), env: ENV,
      metrics: p.failed ? [] : [{ name: "latency_ms", unit: "ms", samples }], status: p.failed ? "failed" : "ok",
      ...(p.failed ? { failure_note: "Sample failure: server ran out of memory at batch 8." } : {}),
      is_baseline: p.baseline, is_warmup: p.warmup, started_at: started.toISOString(), ended_at: new Date(started.getTime() + 30_000).toISOString(),
      command: `atlas-lab run sample_bench.py --config ${p.name}`,
    };
    const configId = await repo.upsertConfig(projectId, p.name, p.config, upload.config_hash);
    const runId = await repo.insertRun({
      projectId, configId, upload, envFingerprint: envFingerprint(ENV), source: "upload", runnerTokenId: null, uploadSha256: sha256(JSON.stringify(upload)),
      isMock: true, summaries: new Map(samples.length ? [["latency_ms", describe(samples)]] : []), gpu: [], userId, rawDir: getEnv().RAW_DATA_DIR,
    });
    if (samples.length) await enqueueJob(userId, "stats.summarize", { run_id: runId, metrics: [{ name: "latency_ms", values: samples }] }, { run_id: runId, sample: true });
  }
  return projectId;
}
